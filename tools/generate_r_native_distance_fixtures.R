# Run from RdistNN_stata. Requires the loaded sibling Rcpp DLL; never silently
# label an R fallback as native. Does not change the R source or installation.
args <- commandArgs(trailingOnly=TRUE)
root <- normalizePath(if(length(args)) args[1] else "../RdistNN",mustWork=TRUE)
pkgload::load_all(root,compile=FALSE,quiet=TRUE)
getr <- function(name) get(name,envir=asNamespace("RdistNN"))
old_options <- options(RdistNN.use_compiled=TRUE)
symbols <- as.vector(outer(c("l1","l2"),c("","_batch","_scaled","_scaled_batch"),
  function(metric,suffix) paste0("rustat_dist_",metric,suffix)))
for(symbol in symbols) if(is.null(getr(".rdistnn_compiled_fun")(symbol))) stop("Compiled R function unavailable: ",symbol)
ranks <- function(D) {
  # Independent distance-then-row reference; no package ordering helper is used.
  matrix(vapply(seq_len(ncol(D)), function(j) {
    ord <- order(D[,j], seq_len(nrow(D)))
    out <- integer(nrow(D)); out[ord] <- seq_len(nrow(D)); out
  }, integer(nrow(D))), nrow(D), ncol(D))
}
lines <- c("// Generated by tools/generate_r_native_distance_fixtures.R; do not edit.",
  "// C calls the loaded Rcpp DLL; R disables RdistNN.use_compiled.",
  "// Both actual references retained to expose any native/fallback disagreement.",
  paste0("// R commit: ",system2("git",c("-C",shQuote(root),"rev-parse","HEAD"),stdout=TRUE)),
  paste0("// Source md5: ",paste(tools::md5sum(file.path(root,c("inst/include/distance_arithmetic.hpp","src/dist_l1.cpp","src/dist_l2.cpp","R/dist_l1.R","R/dist_l2.R","R/utils-scale.R","R/utils-compiled.R"))),collapse=" ")))
emit <- function(name,value) {
  value <- as.matrix(value)
  rr <- apply(value,1,function(z)paste(sprintf("%.17g",z),collapse=","))
  lines <<- c(lines,sprintf("matrix ND_%s = (%s)",name,paste(rr,collapse=" \\ ")))
}
summary <- character()
export_case <- function(id,X,X0,metric,rule="none",scale_vec=c(-2,0,4),eps=1e-8) {
  scaled <- rule!="none"
  spec <- if(scaled) getr(paste0("distance_",metric,"_scaled"))(rule,scale_vec,eps) else getr(paste0("distance_",metric))()
  ctx <- if(is.function(spec$setup)) spec$setup(X) else NULL
  options(RdistNN.use_compiled=TRUE)
  native <- spec$eval_batch(X,X0,ctx)
  scalar <- vapply(seq_len(nrow(X0)),function(j)spec$eval(X,X0[j,],ctx),numeric(nrow(X)))
  if(!identical(native,scalar)) stop("R native batch/scalar mismatch: ",id)
  inv <- if(scaled) ctx$inv_s else rep(1,ncol(X))
  argv <- list(X,X0)
  if(scaled) argv <- c(argv,list(inv))
  if(metric=="l2") argv <- c(argv,list(FALSE))
  direct <- do.call(getr(paste0("rustat_dist_",metric,if(scaled)"_scaled_batch" else "_batch")),argv)
  if(!identical(native,direct)) stop("Spec disagrees with actual compiled function: ",id)
  # Literal scalar arithmetic, independent of the distance implementation.
  literal <- matrix(0,nrow(X),nrow(X0))
  for(j in seq_len(nrow(X0))) for(i in seq_len(nrow(X))) {
    accum <- 0
    for(k in seq_len(ncol(X))) {
      d <- (X[i,k]-X0[j,k])*inv[k]
      accum <- accum+if(metric=="l1")abs(d) else d*d
    }
    literal[i,j] <- if(metric=="l1")accum else sqrt(accum)
  }
  if(!identical(native,literal)) stop("Native disagrees with literal arithmetic: ",id)
  options(RdistNN.use_compiled=FALSE)
  for(symbol in symbols) if(!is.null(getr(".rdistnn_compiled_fun")(symbol))) stop("Fallback option failed")
  fallback <- spec$eval_batch(X,X0,ctx)
  scalar_r <- vapply(seq_len(nrow(X0)),function(j)spec$eval(X,X0[j,],ctx),numeric(nrow(X)))
  if(!identical(fallback,scalar_r)) stop("R fallback batch/scalar mismatch: ",id)
  emit(paste0(id,"_inv"),matrix(inv,nrow=1)); emit(paste0(id,"_scale"),matrix(1/inv,nrow=1))
  emit(paste0(id,"_C"),native); emit(paste0(id,"_R"),fallback)
  emit(paste0(id,"_rankC"),ranks(native)); emit(paste0(id,"_rankR"),ranks(fallback))
  discrepancy <- sum(ranks(native)!=ranks(fallback))
  emit(paste0(id,"_rankdiff"),discrepancy)
  summary <<- c(summary,sprintf("%s: max relative distance difference %.4g; differing rank entries %d",id,
    max(abs(native-fallback)/pmax(1,abs(native))),discrepancy))
}
X <- cbind(c(-3,-1,0,0,2,8),c(1,4,2,2,9,15),rep(5,6))
