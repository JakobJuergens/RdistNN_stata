  spec <- getr("distance_l2_scaled")("custom",c(1,2,3))
  bad <- list(function()spec$eval_batch(X,X0[,1:2],NULL),
    function()spec$eval_batch(replace(X,1,NA_real_),X0,NULL),
    function()spec$eval_batch(X,replace(X0,1,Inf),NULL),
    function()spec$eval_batch(X,X0,list(inv_s=c(1,2))),
    function()spec$eval_batch(X,X0,list(inv_s=c(1,2,Inf))),
