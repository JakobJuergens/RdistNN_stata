# Run from RdistNN_stata; all numeric values come from the sibling R package.
r_root <- normalizePath(file.path("..", "RdistNN"), mustWork = TRUE)
pkgload::load_all(r_root, compile = FALSE, quiet = TRUE)
lines <- c("// Generated by tools/generate_r_reuse_fixtures.R; do not hand edit.",
  paste0("// R reference: ", system2("git", c("-C", shQuote(r_root), "rev-parse", "HEAD"), stdout = TRUE)),
  "// Joint covariance is formed from explicit frozen-geometry deletions using R weights.")
emit <- function(name, value) {
  value <- as.matrix(value)
  rows <- apply(value, 1, function(z) paste(ifelse(is.finite(z), sprintf("%.17g", z), "."), collapse = ", "))
  lines <<- c(lines, sprintf("matrix R_reuse_%s = (%s)", name, paste(rows, collapse = paste0(" ",intToUtf8(92)," "))))
}
x <- (1:12)/4; X <- matrix(x,ncol=1); X0 <- matrix(c(.25,1.25,2.75),ncol=1)
y <- sin(x)+x; den <- 1+x/10; D <- cbind(2*y,cos(x))
scores <- plqr_score_matrix(data.frame(y=y,d1=D[,1],d2=D[,2],g=0,md1=0,md2=0),
  y_col="y",D_cols=c("d1","d2"),g_col="g",mD_cols=c("md1","md2"),theta=c(.3,-.2),tau=.5)
for (method in c("exact","asymp")) {
  W <- weights_dnn(X=X,X0=X0,k=2L,s=4L,method=method)$W
  for (family in c("np","cate","clate","plqr")) {
    signal <- switch(family,np=matrix(y,ncol=1),cate=matrix(y,ncol=1),clate=cbind(y,den),plqr=scores)
    fit <- t(signal)%*%W
    theta <- if (family=="clate") fit[1,]/fit[2,] else NULL
    if (family=="clate") fit <- matrix(theta,nrow=1)
    # Scalar/PLQR estimators are linear in frozen signals; CLATE covariance
    # linearizes paired component deletions at the full-sample ratio.
    loo <- t(vapply(1:12,function(i) {
      wi <- weights_dnn(X=X[-i,,drop=FALSE],X0=X0,k=2L,s=4L,method=method)$W
      v <- t(signal[-i,,drop=FALSE])%*%wi
      if(family=="clate") as.vector((v[1,]-theta*v[2,])/as.vector(t(signal)%*%W)[seq(2,6,2)]) else as.vector(v)
    }, numeric(length(fit))))
    centered <- sweep(loo,2,colMeans(loo))
    V <- crossprod(centered)*11/12
    emit(paste0(family,"_",method,"_fit"),fit)
    emit(paste0(family,"_",method,"_vcov"),V)
  }
}
tie <- plqr_dnn(X=rbind(c(1,2^-26),c(1,0),c(2,0)),
  D=matrix(c(1,3,1),ncol=1),g=rep(0,3),mD=matrix(0,3,1),
  Y=rep(10,3),theta_eval=0,x0=c(0,0),s=2L)
emit("plqr_neartie",tie$moment)
writeLines(lines,"tests/fixtures/r_reuse_fixtures.do")
