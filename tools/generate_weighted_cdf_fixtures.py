"""Export exact binary CDF boundary fixtures to R and Mata test suites.

Inputs are represented exact-DNN tables (k=1, s=2), permuted over ordered
outcomes. Fraction is a fixture-only oracle: rounded exact totals and prefixes
are checked against the specified serial double Neumaier calculation.
"""
import argparse
import csv
from fractions import Fraction
from pathlib import Path


def compensated(values):
    high = low = 0.0
    for value in values:
        next_high = high + value
        low += ((high - next_high) + value if abs(high) >= abs(value)
                else (value - next_high) + high)
        high = next_high
    return high + low


def stata_hex(value):
    if value == 0:
        return "0"
    mantissa, exponent = value.hex().split("p")
    exponent = int(exponent)
    return ("+" + mantissa.removeprefix("0x") + "X" +
            ("-" if exponent < 0 else "+") + f"{abs(exponent):03x}")


def products(root, r_root):
    with (root / "tests/fixtures/weighted_cdf_inputs.csv").open() as source:
        rows = list(csv.DictReader(source))
    cases = {}
    for row in rows:
        cases.setdefault(row["case"], []).append(row)
    mata = ["// Generated by tools/generate_weighted_cdf_fixtures.py; do not edit."]
    result = []
    for name, case in cases.items():
        weights = [float.fromhex(row["weight_hex"]) for row in case]
        prob = float.fromhex(case[0]["prob_hex"])
        mass = sum(map(Fraction.from_float, weights), Fraction())
        assert compensated(weights) == float(mass)
        prefix = Fraction()
        expected = None
        for i, weight in enumerate(weights, 1):
            prefix += Fraction.from_float(weight)
            assert compensated(weights[:i]) == float(prefix)
            if expected is None and float(prefix) / float(mass) >= prob:
                expected = i
        assert expected is not None
        result.extend(dict(row, expected=str(expected)) for row in case)
        joined_weights = " \\ ".join(map(stata_hex, weights))
        mata.extend([
            f"matrix WD_W=({joined_weights})",
            f"scalar WD_P={stata_hex(prob)}",
            f'mata: st_numscalar("wd_boundary",rdistnn_weighted_quantile((1::{len(weights)}),st_matrix("WD_W"),st_numscalar("WD_P")))',
            f'test_assert "{name}: canonical selected observation" scalar(wd_boundary)=={expected}',
        ])
    import io
    data = io.StringIO(newline="")
    writer = csv.DictWriter(data, fieldnames=[*rows[0], "expected"], lineterminator="\n")
    writer.writeheader()
    writer.writerows(result)
    return {
        root / "tests/fixtures/weighted_cdf_fixtures.do": "\n".join(mata) + "\n",
        r_root / "tests/testthat/fixtures/weighted-cdf.csv": data.getvalue(),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--r-root", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    r_root = args.r_root or root.parent / "RdistNN"
    for path, content in products(root, r_root).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale CDF fixture: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Weighted CDF fixtures verified" if args.check else "Weighted CDF fixtures generated")
