# Run from RdistNN_stata. Fixtures require the sibling's current native build.
root <- normalizePath("../RdistNN", mustWork = TRUE)
pkgload::load_all(root, compile = FALSE, quiet = TRUE)
getr <- function(name) get(name, envir = asNamespace("RdistNN"))
old <- options(RdistNN.use_compiled = TRUE)
for (kernel in c("rustat_compensated_sum", "rustat_compensated_crossprod",
                 "rustat_jackknife_rank_full")) {
  if (!is.function(getr(".rdistnn_compiled_fun")(kernel))) {
    stop("Native fixture kernel unavailable: ", kernel,
      ". Rebuild the sibling R package before generating fixtures.", call. = FALSE)
  }
}
lines <- c("// Generated by tools/generate_r_accumulation_fixtures.R; do not edit.",
  "// Hexadecimal inputs preserve the represented doubles across languages.",
  "// Native and forced-R outputs are checked before export.")
hex <- function(x) {
  if (x == 0) return("0")
  bits <- strsplit(sprintf("%a", abs(x)), "p", fixed = TRUE)[[1L]]
  significand <- sub("^0x", "", bits[1L])
  if (!grepl(".", significand, fixed = TRUE)) significand <- paste0(significand, ".")
  fraction <- strsplit(significand, ".", fixed = TRUE)[[1L]]
  digits <- if (length(fraction) == 2L) fraction[2L] else ""
  significand <- paste0(fraction[1L], ".", digits, strrep("0", 13L - nchar(digits)))
  exponent <- as.integer(bits[2L])
  paste0(if (x < 0) "-" else "+", significand, "X",
    if (exponent < 0) "-" else "+", sprintf("%03x", abs(exponent)))
}
emit <- function(name, value) {
  if (is.null(value)) stop("Missing fixture value: ", name)
  value <- as.matrix(value)
  stopifnot(all(is.finite(value)))
  rows <- apply(value, 1L, function(z) paste(vapply(z, hex, character(1L)), collapse = ","))
  lines <<- c(lines, sprintf("matrix AC_%s = (%s)", name, paste(rows, collapse = " \\ ")))
}
set.seed(7183)
for (i in 1:32) {
  powers <- 2^sample(0:80, 8, TRUE)
  x <- sample(c(powers, -powers, 1))
  answers <- vapply(c(TRUE, FALSE), function(native) {
    options(RdistNN.use_compiled = native)
    getr(".compensated_sum")(x)
  }, numeric(1L))
  stopifnot(identical(answers, c(1, 1)))
  emit(paste0("sum", i), x)
}
n <- 24L
signal <- cbind(sin(seq_len(n)) + seq_len(n) / 16,
  1 + cos(seq_len(n)) / 8)
ranks <- cbind(seq_len(n), rev(seq_len(n)), c(2:n, 1L))
emit("signal", signal); emit("ranks", ranks)
for (method in c("exact", "asymp")) for (kind in c("dnn", "tdnn")) {
  rule <- if (kind == "dnn") {
    getr(paste0("rank_weight_dnn_", method))(k = 2, s = 7)
  } else getr(paste0("rank_weight_tdnn_", method))(s1 = 4, s2 = 7, dim = 3)
  full <- rule$table(n); table <- rule$table(n - 1L)
  answers <- lapply(c(TRUE, FALSE), function(native) {
    options(RdistNN.use_compiled = native)
    getr("jackknife_rank_full")(ranks, signal, full, table)
  })
  stopifnot(identical(answers[[1L]], answers[[2L]]))
  id <- paste(kind, method, sep = "_")
  emit(paste0(id, "_full"), full); emit(paste0(id, "_table"), table)
  emit(paste0(id, "_theta"), answers[[1L]]$theta0)
  emit(paste0(id, "_loo"), matrix(answers[[1L]]$theta_loo, nrow = n))
}

X <- cbind(seq_len(n) / 8, (seq_len(n) %% 5) / 4)
Y <- signal[, 1L]; den <- signal[, 2L]
targets <- X[c(2L, 13L), , drop = FALSE]
pred_targets <- X[c(19L, 2L, 19L), , drop = FALSE]
emit("X", X); emit("Y", Y); emit("den", den)
emit("targets", targets); emit("predict", pred_targets)
for (method in c("exact", "asymp")) for (kind in c("np", "cate", "ratio", "tdnn")) {
  fits <- lapply(c(TRUE, FALSE), function(native) {
    options(RdistNN.use_compiled = native)
    switch(kind,
      np = getr("np_dnn")(X = X, Y = Y, X0 = targets, s = 7, method = method),
      cate = getr("cate_dnn")(X = X, pseudo_outcome = Y, X0 = targets, s = 7, method = method),
      ratio = getr("affine_ratio_dnn")(X = X, numerator = Y, denominator = den,
        X0 = targets, s = 7, method = method),
      tdnn = getr("np_tdnn")(X = X, Y = Y, X0 = targets, s1 = 4, s2 = 7, method = method))
  })
  point <- function(fit) if (kind %in% c("np", "tdnn")) fit$mu else if (kind == "cate") fit$tau else fit$theta
  stopifnot(identical(point(fits[[1L]]), point(fits[[2L]])),
    isTRUE(all.equal(fits[[1L]]$se, fits[[2L]]$se, tolerance = 1e-13)))
  id <- paste(kind, method, sep = "_")
  emit(paste0(id, "_point"), matrix(point(fits[[1L]]), 1))
  emit(paste0(id, "_se"), matrix(as.numeric(fits[[1L]]$se), 1))
  if (kind %in% c("np", "tdnn")) {
    emit(paste0(id, "_vcov"), vcov(fits[[1L]]))
    options(RdistNN.use_compiled = TRUE)
    p1 <- predict(unserialize(serialize(fits[[1L]], NULL)), X0 = pred_targets, se.fit = TRUE)
    options(RdistNN.use_compiled = FALSE)
    p2 <- predict(unserialize(serialize(fits[[2L]], NULL)), X0 = pred_targets, se.fit = TRUE)
    stopifnot(identical(p1$fit, p2$fit), isTRUE(all.equal(p1$se.fit, p2$se.fit, tolerance = 1e-13)))
    emit(paste0(id, "_pred"), matrix(p1$fit, 1))
    emit(paste0(id, "_pred_se"), matrix(p1$se.fit, 1))
  }
}
# Supplied-coefficient PLQR moments use the same weighted signal primitive.
D <- matrix((seq_len(n) %% 7) / 3, ncol = 1)
emit("D", D)
for (method in c("exact", "asymp")) {
  fits <- lapply(c(TRUE, FALSE), function(native) {
    options(RdistNN.use_compiled = native)
    getr("plqr_dnn")(X = X, Y = Y, D = D, mD = matrix(0, n, 1),
      g = rep(0, n), theta_eval = 0, x0 = targets[1L, ], s = 7, method = method)
  })
  stopifnot(identical(fits[[1L]]$moment, fits[[2L]]$moment))
  emit(paste0("plqr_", method, "_point"), fits[[1L]]$moment)
  emit(paste0("plqr_", method, "_se"), fits[[1L]]$moment_se)
}
options(old)
writeLines(lines, "tests/fixtures/r_accumulation_fixtures.do")
