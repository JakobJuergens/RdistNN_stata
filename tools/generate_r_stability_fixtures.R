# Run from RdistNN_stata against the actual compiled sibling and forced R path.
root <- normalizePath("../RdistNN", mustWork = TRUE)
pkgload::load_all(root, compile = FALSE, quiet = TRUE)
getr <- function(name) get(name, envir = asNamespace("RdistNN"))
old <- options(RdistNN.use_compiled = TRUE)
if (!is.function(getr(".rdistnn_compiled_fun")("rustat_dist_l2_batch"))) {
  stop("Stability fixtures require the actual compiled R distance kernel.")
}
sources <- c("R/wrank-probability.R", "R/wrank-dnn_approx.R",
             "R/wrank-tdnn_exact.R", "R/wrank-tdnn_approx.R",
             "R/dist_l2.R", "src/dist_l2.cpp", "R/utils-scale.R",
             "inst/include/distance_arithmetic.hpp")
lines <- c("// Generated by tools/generate_r_stability_fixtures.R; do not edit.",
  "// Actual native/forced R distance paths and independent analytic tail checks.",
  paste0("// R source md5: ", paste(tools::md5sum(file.path(root, sources)), collapse = " ")))
emit <- function(name, value) {
  value <- as.matrix(value)
  if (any(!is.finite(value))) stop("Nonfinite fixture: ", name)
  rows <- apply(value, 1L, function(z) paste(sprintf("%.17g", z), collapse = ","))
  lines <<- c(lines, sprintf("matrix ST_%s = (%s)", name, paste(rows, collapse = " \\ ")))
}
for (k in c(1L, 3L, 80L)) {
  w <- getr("dnn_weights_asymp_full_from_ranks")(1:100, k, 80L)$w_rank
  if (k == 1L) {
    analytic <- exp(80 * log1p(-.79)) *
      (-expm1(80 * (log1p(-.8) - log1p(-.79))))
    stopifnot(w[80L] > 0, abs(w[80L] / analytic - 1) < 1e-12)
  }
  emit(paste0("W", k), w)
}
emit("COEF", t(vapply(list(c(1000,1001,50), c(10000,10001,100)),
  function(z) getr(".tdnn_scalars")(z[1],z[2],z[3]), numeric(2))))
# Independent exact integer combinations and 90-digit elementary arithmetic.
# Python is needed only to regenerate fixtures, never for Stata package use.
python <- Sys.which("python3")
if (!nzchar(python)) stop("Regenerating stability fixtures requires Python 3.")
oracle_code <- paste(c(
  "from decimal import Decimal, localcontext",
  "from math import comb",
  "with localcontext() as c:",
  " c.prec=90",
  " w1=-1/((Decimal(2)/100*(Decimal(80)/79).ln()).exp()-1)",
  " for r in range(1,101):",
  "  a=Decimal(comb(100-r,78))/comb(100,79) if r<=22 else Decimal(0)",
  "  b=Decimal(comb(100-r,79))/comb(100,80) if r<=21 else Decimal(0)",
  "  print(format(w1*a+(1-w1)*b,'.17g'))"), collapse="\n")
oracle <- scan(text=system2(python,c("-c",shQuote(oracle_code)),stdout=TRUE),quiet=TRUE)
stopifnot(length(oracle)==100L)
emit("TD_exact_oracle",oracle)
for (method in c("exact", "asymp")) {
  fun <- getr(paste0("tdnn_rank_table_", method))
  table <- fun(100L,79L,80L,100L)
  if (method=="exact") stopifnot(max(abs(table-oracle))<1e-9*max(abs(oracle)))
  emit(paste0("TD_", method), table)
}
count <- 0L
for (size in c("huge", "tiny")) {
  h <- if (size == "huge") 1e200 else 1e-200
  i <- seq_len(12)
  X <- cbind((i - 6) / 5, sin(i)) * h
  Y <- sin(i / 3) + i / 50
  A <- rbind(c(-.5,0),c(0,.2),c(-.5,0)) * h
  B <- rbind(c(.7,-.1),c(-.2,.1),c(.7,-.1)) * h
  emit(paste0(size,"_X"),X); emit(paste0(size,"_Y"),Y)
  emit(paste0(size,"_A"),A); emit(paste0(size,"_B"),B)
  for (metric in c("l2", "l2_scaled")) for (method in c("exact","asymp")) {
    id <- paste(size,metric,method,sep="_")
    spec <- if (metric == "l2") getr("distance_l2")() else
      getr("distance_l2_scaled")("custom",scale_vec=c(2,4))
    results <- lapply(c(TRUE,FALSE), function(compiled) {
      options(RdistNN.use_compiled=compiled)
      if (!compiled) stopifnot(is.null(getr(".rdistnn_compiled_fun")("rustat_dist_l2_batch")))
      fit <- getr("np_dnn")(X=X,Y=Y,X0=A,k=2L,s=4L,method=method,
        distance=spec,return=c("ranks","dx"))
      predictions <- predict(unserialize(serialize(fit,NULL)),X0=B,se.fit=TRUE)
      list(fit=as.numeric(fit$mu),V=vcov(fit),D=spec$eval_batch(X,A,spec$setup(X)),
           prediction=as.numeric(predictions$fit),prediction_se=as.numeric(predictions$se.fit))
    })
    stopifnot(isTRUE(all.equal(results[[1]],results[[2]],tolerance=1e-13)))
    stopifnot(identical(results[[1]]$D, results[[2]]$D),
      identical(apply(results[[1]]$D,2L,rank,ties.method="first"),
                apply(results[[2]]$D,2L,rank,ties.method="first")))
    ref <- results[[1]]
    emit(paste0(id,"_fit"),matrix(ref$fit,1L))
    emit(paste0(id,"_V"),ref$V)
    emit(paste0(id,"_D"),ref$D)
    emit(paste0(id,"_ranks"),apply(ref$D,2L,rank,ties.method="first"))
    emit(paste0(id,"_pred"),matrix(ref$prediction,1L))
    emit(paste0(id,"_pse"),matrix(ref$prediction_se,1L))
    count <- count+1L
  }
}
options(old)
writeLines(lines,"tests/fixtures/r_stability_fixtures.do")
cat("Generated",count,"extreme fitted/prediction cases from real native and R fallback paths; weight analytic checks passed.\n")
