    args <- c(args,list(Y=p$Y,D=p$D,A=p$A,e=p$e,m_y0=p$my0,m_y1=p$my1,
      m_d0=p$md0,m_d1=p$md1,one_sided=a$one_sided,clip=a$clip))
    f <- suppressWarnings(do.call(clate_dnn,args))
    input <- cbind(a$X,as.matrix(p))
    a$signal <- f$signals
  }
  m <- nrow(a$X0); n <- nrow(a$X)
  CV <- matrix(NA_real_,2L*m,2L*m); V <- matrix(NA_real_,m,m)
  if (a$active) {
    L <- do.call(cbind,lapply(seq_len(m),function(j) f$deletions[,,j]))
    C <- sweep(L,2L,colMeans(L),"-")
    CV <- (n-1)/n*crossprod(C)
    # Numerical failure of ratio/omega can leave paired component covariance
    # available. Preserve exactly the blocks R exposes, independently of SE.
    paired_finite <- vapply(f$component_vcov,function(v) all(is.finite(v)),logical(1L))
    for (j in seq_len(m)) if (!paired_finite[j]) {
      ii <- (2L*j-1L):(2L*j); CV[ii,] <- CV[,ii] <- NA_real_
    }
    G <- vapply(seq_len(m),function(j) {
      C[,2L*j-1L]/f$components[j,2L]-f$theta[j]*(C[,2L*j]/f$components[j,2L])
    },numeric(n))
    for (j in seq_len(m)) for (h in seq_len(m)) {
      if (is.finite(f$se[j]) && is.finite(f$se[h])) V[j,h] <- (n-1)/n*sum(G[,j]*G[,h])
    }
    close(matrix(diag(V),1L),matrix(vapply(f$theta_vcov,function(v) v[1,1],numeric(1L)),1L))
  }
  if (a$independent && n>1L) {
    ref <- oracle(a$X,a$X0,a$signal,a$k,a$s,a$method,a$distance,a$active,f$.model$dx)
    close(f$components,ref$components)
    if (a$active) {
      close(L,ref$loo); close(CV,ref$cv)
      # Zero-score rounding may differ by ~1e-30; compare at an absolute floor.
      close(V,ref$V)
    }
  }
  lines <- c(lines,sprintf("// Case %d: %s",id,a$label),
    sprintf("local ca_label%d %s",id,shQuote(a$label,type="cmd")),
    sprintf("local ca_p%d %d",id,ncol(a$X)),
    sprintf("local ca_nuisance%d %d",id,!is.null(a$nuisance)),
    sprintf("local ca_options%d k(%d) s(%d) method(%s) distance(%s) denominatortol(%.17g)%s%s",
      id,a$k,a$s,a$method,a$distance,a$tol,if(a$active) "" else " nose",
      if(!is.null(a$nuisance)) sprintf(" clip(%.17g)%s",a$clip,if(a$one_sided) " onesided" else "") else ""))
  emit(paste0("input",id),input); emit(paste0("targets",id),a$X0)
  emit(paste0("theta",id),matrix(f$theta,1L)); emit(paste0("components",id),f$components)
  emit(paste0("CV",id),CV); emit(paste0("V",id),V)
  emit(paste0("se",id),matrix(if(is.null(f$se)) rep(NA_real_,m) else f$se,1L))
