emit <- function(name, value) {
  value <- as.matrix(value)
  rows <- apply(value, 1L, function(z) paste(ifelse(is.finite(z), sprintf("%.17g", z), "."), collapse = ", "))
  lines <<- c(lines, sprintf("matrix CA_%s = (%s)", name, paste(rows, collapse = " \\ ")))
}
close <- function(x, y, tol = 2e-10) {
  stopifnot(identical(dim(x), dim(y)), identical(unname(is.finite(x)), unname(is.finite(y))))
  ok <- is.finite(x) & is.finite(y)
  if (any(ok)) stopifnot(max(abs(x[ok] - y[ok])) <= tol * max(1, abs(y[ok])))
}
distance_matrix <- function(X, X0, distance) {
  Si <- if (distance == "mahalanobis") {
    # Full-rank inverse, or a Moore-Penrose inverse from independent eigendecomposition.
    S <- cov(X)
    eig <- eigen(S, symmetric = TRUE)
    ei <- ifelse(eig$values > 1e-10 * max(eig$values), 1 / eig$values, 0)
    eig$vectors %*% diag(ei, nrow = length(ei)) %*% t(eig$vectors)
  } else diag(ncol(X))
  vapply(seq_len(nrow(X0)), function(j) {
    Z <- sweep(X, 2L, X0[j, ], "-")
    rowSums((Z %*% Si) * Z)
  }, numeric(nrow(X)))
}
oracle <- function(X, X0, signal, k, s, method, distance, active, dx) {
  n <- nrow(X); m <- nrow(X0)
  # Verify the chosen metric independently, then use its actual represented
  # distances for equality. An independent quadratic form can round a true
  # equality differently from the fitted whitening/distance implementation.
  close(dx^2,distance_matrix(X,X0,distance))
  strict_order <- function(ids,j) order(dx[ids,j],ids)
  average <- function(ids, j) {
    nn <- length(ids)
    if (method == "exact") {
      # Enumerate the symmetric boundary-tie kernel after actual removal;
      # package rank-weight/grouping/deletion helpers are never called.
      subsets <- combn(ids, s, simplify = FALSE)
      w <- numeric(nn)
      for (ii in subsets) {
        boundary <- sort(dx[ii,j])[k]
        closer <- ii[dx[ii,j]<boundary]
        equal <- ii[dx[ii,j]==boundary]
        w[match(closer,ids)] <- w[match(closer,ids)] + 1/(k*length(subsets))
        w[match(equal,ids)] <- w[match(equal,ids)] +
          (k-length(closer))/(k*length(equal)*length(subsets))
      }
    } else {
      ord <- strict_order(ids,j)
      # Integrate polynomial beta densities, rather than package rank tables
      # or deletion helpers or differences of pbeta.
      ranked <- vapply(seq_len(nn), function(r) {
        sum(vapply(seq_len(k), function(i) {
          integrate(function(u) dbeta(u, i, s-i+1L), (r-1)/nn, r/nn,
                    rel.tol = 1e-12, abs.tol = 1e-15)$value
        }, numeric(1L))) / k
      }, numeric(1L))
      w <- numeric(nn); w[ord] <- ranked
    }
    done <- rep(FALSE,nn)
    for (ii in seq_len(nn)) if (!done[ii]) {
      members <- dx[ids,j]==dx[ids[ii],j]
      w[members] <- sum(w[members])/sum(members)
      done[members] <- TRUE
    }
    colSums(signal[ids, , drop = FALSE] * w)
  }
  components <- t(vapply(seq_len(m), function(j) average(seq_len(n), j), numeric(2L)))
  if (!active) return(list(components = components))
  loo <- matrix(NA_real_, n, 2L*m)
  for (j in seq_len(m)) for (i in seq_len(n)) {
    loo[i, (2L*j-1L):(2L*j)] <- average(setdiff(seq_len(n), i), j)
  }
  centered <- sweep(loo, 2L, colMeans(loo), "-")
  cv <- (n-1)/n * crossprod(centered)
  theta <- components[, 1L]/components[, 2L]
  G <- vapply(seq_len(m), function(j) {
    (centered[, 2L*j-1L] - theta[j]*centered[, 2L*j])/components[j, 2L]
  }, numeric(n))
  list(components = components, loo = loo, cv = cv, V = (n-1)/n*crossprod(G))
}
