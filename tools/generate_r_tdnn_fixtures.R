# Run from RdistNN_stata. Deterministic sibling-R authority and explicit LOO.
r_root <- normalizePath(file.path("..", "RdistNN"), mustWork = TRUE)
pkgload::load_all(r_root, compile = FALSE, quiet = TRUE)
lines <- c("// Generated by tools/generate_r_tdnn_fixtures.R; do not hand edit.",
  paste0("// R reference: ", system2("git", c("-C",shQuote(r_root),"rev-parse","HEAD"),stdout=TRUE)),
  "// Cross-target covariance uses independent explicit reduced-sample weights.")
emit <- function(name, value) {
  value <- as.matrix(value)
  rows <- apply(value,1,function(z) paste(sprintf("%.17g",z),collapse=", "))
  lines <<- c(lines,sprintf("matrix R_tdnn_%s = (%s)",name,paste(rows,collapse=paste0(" ",intToUtf8(92)," "))))
}
X <- rbind(c(-1,0),c(0,-1),c(0,0),c(1,0),c(0,1),c(1,1),c(-1,-1),
  c(2,-.5),c(-.5,1.5),c(.75,-1.25),c(1.5,.5),c(-1.5,.75))
X0 <- rbind(c(.2,-.1),c(-.5,.75),c(1.2,.4))
y <- .7*X[,1]-.4*X[,2]+seq_len(nrow(X))/20
for(method in c("exact","asymp")) {
  rw <- if(method=="exact") rank_weight_tdnn_exact(3L,6L,2L) else rank_weight_tdnn_asymp(3L,6L,2L)
  W <- weights_tdnn(X=X,X0=X0,s1=3L,s2=6L,dim=2L,method=method)$W
  loo <- t(vapply(seq_len(nrow(X)),function(i) {
    wi <- weights_tdnn(X=X[-i,,drop=FALSE],X0=X0,s1=3L,s2=6L,dim=2L,method=method)$W
    as.vector(y[-i]%*%wi)
  },numeric(nrow(X0))))
  centered <- sweep(loo,2,colMeans(loo))
  emit(paste0(method,"_table"),rw$table(nrow(X)))
  emit(paste0(method,"_weights"),W)
  emit(paste0(method,"_fit"),matrix(y%*%W,nrow=1))
  emit(paste0(method,"_vcov"),crossprod(centered)*(nrow(X)-1)/nrow(X))
}
emit("asymp_dim4_nonorm",rank_weight_tdnn_asymp(3L,6L,4L,normalize=FALSE)$table(nrow(X)))
writeLines(lines,"tests/fixtures/r_tdnn_fixtures.do")
