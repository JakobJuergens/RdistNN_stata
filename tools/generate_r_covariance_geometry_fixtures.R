# Run from RdistNN_stata against the sibling's actual native and R engines.
root <- normalizePath("../RdistNN", mustWork = TRUE)
pkgload::load_all(root, compile = FALSE, quiet = TRUE)
getr <- function(name) get(name, envir = asNamespace("RdistNN"))
old <- options(RdistNN.use_compiled = TRUE)
if (!is.function(getr(".rdistnn_compiled_fun")("rustat_dist_l2_batch")) ||
    !is.function(getr(".rdistnn_compiled_fun")("rustat_jackknife_rank_full")))
  stop("Fixtures require both compiled R kernels.")
lines <- c("// Generated by tools/generate_r_covariance_geometry_fixtures.R; do not edit.",
  "// Shared numeric inputs; native and forced R outputs checked before export.",
  paste0("// R source md5: ", paste(tools::md5sum(file.path(root,
    c("R/dist_mahal.R", "R/utils-covariance.R"))), collapse = " ")))
emit <- function(name, value) {
  value <- as.matrix(value)
  if (any(!is.finite(value))) stop("Nonfinite fixture: ", name)
  rows <- apply(value, 1L, function(z) paste(sprintf("%.17g", z), collapse = ","))
  lines <<- c(lines, sprintf("matrix CG_%s = (%s)", name, paste(rows, collapse = " \\ ")))
}
x <- -2:2; z <- c(1, -1, 0, -1, 1)
a <- -17 / 8 + c(-1, 1) * 2^-10
base <- rbind(c(2, 1), c(2, -1), c(-2, 1), c(-2, -1), c(0, 0))
cases <- list(
  near = list(X = cbind(x, x + 2^-22 * z), A = cbind(a, a - 2^-22 / 8), rank = 2L),
  wide = list(X = rbind(c(1,0,1,0),c(0,1,0,1),c(-1,-1,-1,-1)),
    A = matrix(c(.25,.125,.25,.125),1), rank = 2L),
  singular = list(X = cbind(x,2*x,z), A = matrix(c(.25,-.5,.125),1), rank = 2L),
  huge = list(X = base * 2^600, A = matrix(c(.25,.125),1) * 2^600, rank = 2L),
  tiny = list(X = base * 2^-600, A = matrix(c(.25,.125),1) * 2^-600, rank = 2L),
  offset = list(X = cbind(rep(2^600,3),c(-1,0,1)*2^-600),
    A = matrix(c(2^600,0),1),rank = 1L),
  null = list(X = cbind(c(-1,0,1)*2^-600,0),
    A = matrix(c(0,2^1000),1),rank = 1L))
for (id in names(cases)) {
  case <- cases[[id]]
  spec <- getr("distance_mahalanobis")()
  ctx <- spec$setup(case$X)
  stopifnot(identical(ctx$rank, case$rank))
  outputs <- lapply(c(TRUE,FALSE), function(native) {
    options(RdistNN.use_compiled = native)
    D <- spec$eval_batch(case$X, case$A, ctx)
    ranks <- apply(D,2,rank,ties.method="first")
    list(D = D, ranks = ranks)
  })
  stopifnot(identical(outputs[[1]], outputs[[2]]))
  emit(paste0(id,"_rank"),case$rank)
  emit(paste0(id,"_X"), case$X); emit(paste0(id,"_A"),case$A)
  emit(paste0(id,"_D"), outputs[[1]]$D); emit(paste0(id,"_ranks"),outputs[[1]]$ranks)
}
X <- cbind(c(-2,-1,0,1,2,3),c(1,2,1,-1,0,2)); Y <- c(1,-2,0,3,-1,1)
A <- X[c(1,4),]; B <- X[c(3,1,3),]
emit("X",X); emit("Y",Y); emit("A",A); emit("B",B)
for (method in c("exact","asymp")) for (kind in c("np","tdnn","cate","ratio")) {
  fits <- lapply(c(TRUE,FALSE),function(native) {
    options(RdistNN.use_compiled = native)
    switch(kind,
      np = getr("np_dnn")(X=X,Y=Y,X0=A,s=3,method=method),
      tdnn = getr("np_tdnn")(X=X,Y=Y,X0=A,s1=2,s2=3,method=method),
      cate = getr("cate_dnn")(X=X,pseudo_outcome=Y,X0=A,s=3,method=method),
      ratio = getr("affine_ratio_dnn")(X=X,numerator=Y,denominator=rep(2,6),X0=A,s=3,method=method))
  })
  stopifnot(isTRUE(all.equal(fits[[1]]$se,fits[[2]]$se,tolerance=1e-13)))
  id <- paste(kind,method,sep="_")
  emit(paste0(id,"_se"),matrix(as.numeric(fits[[1]]$se),1))
  if (kind %in% c("np","tdnn")) {
    emit(paste0(id,"_V"),vcov(fits[[1]]))
    pred <- predict(unserialize(serialize(fits[[1]],NULL)),X0=B,se.fit=TRUE)
    emit(paste0(id,"_pred_se"),matrix(pred$se.fit,1))
  }
}
writeLines(lines,"tests/fixtures/r_covariance_geometry_fixtures.do")
options(old)
cat("Exported",length(cases),"geometry cases and eight covariance adapters.\n")
