# Deterministic geometry fixtures from maintained sibling R implementations.
args <- commandArgs(trailingOnly=TRUE)
root <- if(length(args)) args[1] else "../RdistNN"
pkgload::load_all(normalizePath(root,mustWork=TRUE),compile=FALSE,quiet=TRUE)
X <- cbind(c(-3,-1,0,0,2,8),c(1,4,2,2,9,15),rep(5,6))
X0 <- rbind(c(0,2,5),c(1,3,6))
path <- "tests/fixtures/r_geometry_fixtures.do"
con <- file(path,"w")
writeLines("// Generated by tools/generate_r_geometry_fixtures.R; do not edit.",con)
put <- function(name,x) {
  x <- as.matrix(x)
  line <- paste(apply(x,1,function(z)paste(sprintf("%.17g",z),collapse=",")),collapse=" \\ ")
  writeLines(sprintf("matrix %s = (%s)",name,line),con)
}
put("RG_X",X); put("RG_X0",X0)
for(rule in c("sd","mad","iqr","range","custom")) {
  inv <- .compute_inv_scale(X,rule,c(-2,0,4),1e-8)
  put(paste0("RG_scale_",rule),matrix(1/inv,nrow=1))
  for(metric in c("l1","l2")) {
    spec <- if(metric=="l1") distance_l1_scaled(rule,c(-2,0,4),1e-8) else distance_l2_scaled(rule,c(-2,0,4),1e-8)
    D <- spec$eval_batch(X,X0,spec$setup(X))
    ranks <- apply(D,2,function(d)order(order(d,seq_along(d))))
    put(paste0("RG_rank_",metric,"_",rule),ranks)
    put(paste0("RG_",metric,"_",rule),D)
  }
}
