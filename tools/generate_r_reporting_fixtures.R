r_root <- normalizePath(file.path("..", "RdistNN"), mustWork = TRUE)
pkgload::load_all(r_root, compile = FALSE, quiet = TRUE)
lines <- c("// Generated by tools/generate_r_reporting_fixtures.R; do not hand edit.",
  paste0("// Reference RdistNN commit: ", system2("git", c("-C", shQuote(r_root), "rev-parse", "HEAD"), stdout = TRUE)),
  "// R's NP/CATE/CLATE summary methods supply the six columns.",
  "// CLATE paired-signal route uses the shared affine_ratio_dnn summary.",
  "// NP uses the shared six-column regression summary convention.")
emit <- function(name, value) {
  value <- as.matrix(value)
  rows <- apply(value, 1, function(z) paste(ifelse(is.finite(z), sprintf("%.17g", z), "."), collapse = ", "))
  lines <<- c(lines, sprintf("matrix R_report_%s = (%s)", name, paste(rows, collapse = " \\ ")))
}
i <- seq_len(24)
X <- matrix((i-12)/4, ncol = 1)
y <- 2+sin(X[,1])+cos(i)/5
X0 <- matrix(c(-1,0,1), ncol = 1)
for (family in c("cate", "clate", "np")) {
  f <- switch(family,
    cate = cate_dnn(X = X, X0 = X0, pseudo_outcome = y, s = 4L),
    clate = affine_ratio_dnn(X = X, X0 = X0, numerator = y, denominator = rep(1,24), s = 4L),
    np = np_dnn(X = X, X0 = X0, Y = y, s = 4L))
  for (level in c(.90,.95)) {
    tab <- summary(f, level = level)$coefficients
    emit(paste0(family, round(level*100)), tab)
  }
}
zero <- affine_ratio_dnn(X = matrix(1:4, ncol = 1), x0 = 0,
  numerator = rep(2,4), denominator = rep(1,4), s = 2L)
emit("clate_zero_summary", summary(zero)$coefficients)
emit("clate_zero_plot", plot_data_estimates(zero)[, c("estimate", "se", "ci_lower", "ci_upper")])
writeLines(lines, "tests/fixtures/r_reporting_fixtures.do")
