check <- function(actual, expected, label, tolerance = 2e-12) {
  if (!identical(dim(actual), dim(expected)) ||
      any(!is.finite(actual)) || any(!is.finite(expected)) ||
      max(abs(actual - expected)) > tolerance * max(1, abs(expected))) {
    stop(label, ": independent reference mismatch", call. = FALSE)
  }
}

