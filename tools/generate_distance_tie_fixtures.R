# Uniform random ordering within a boundary tie allocates the remaining slots;
# including every boundary neighbor at an equal 1/(q+t) weight is different.
subset_weights <- function(dx, k, s) {
  n <- nrow(dx)
  subsets <- combn(n, s)
  W <- matrix(0, n, ncol(dx))
  for (j in seq_len(ncol(dx))) for (h in seq_len(ncol(subsets))) {
    ids <- subsets[, h]
    boundary <- sort(dx[ids, j])[k]
    closer <- ids[dx[ids, j] < boundary]
    tied <- ids[dx[ids, j] == boundary]
    W[closer, j] <- W[closer, j] + 1 / k
    W[tied, j] <- W[tied, j] + (k - length(closer)) / (k * length(tied))
  }
  W / ncol(subsets)
}
asymptotic_weights <- function(dx, k, s) {
  n <- nrow(dx)
  table <- rowMeans(vapply(seq_len(k), function(h) {
    pbeta(seq_len(n) / n, h, s - h + 1L) -
      pbeta((seq_len(n) - 1L) / n, h, s - h + 1L)
  }, numeric(n)))
  W <- matrix(0, n, ncol(dx))
  for (j in seq_len(ncol(dx))) {
    ord <- order(dx[, j], seq_len(n))
    raw <- numeric(n)
    raw[ord] <- table
    for (i in seq_len(n)) W[i, j] <- mean(raw[dx[, j] == dx[i, j]])
  }
  W
}
oracle_weights <- function(dx, k, s, method) {
  if (method == "exact") subset_weights(dx, k, s) else asymptotic_weights(dx, k, s)
}
covariance <- function(loo) crossprod(sweep(loo, 2L, colMeans(loo))) * (nrow(loo) - 1L) / nrow(loo)
oracle <- function(dx, k, s, method, signal, tdnn = FALSE) {
  weights <- function(d) {
    if (tdnn) -oracle_weights(d, 1L, 3L, method) + 2 * oracle_weights(d, 1L, 6L, method)
    else oracle_weights(d, k, s, method)
  }
  W <- weights(dx)
  loo <- t(vapply(seq_len(nrow(dx)), function(i) {
    as.vector(crossprod(signal[-i, , drop = FALSE], weights(dx[-i, , drop = FALSE])))
  }, numeric(ncol(signal) * ncol(dx))))
  list(W = W, fit = crossprod(signal, W), loo = loo, V = covariance(loo))
}

X <- rbind(c(-1, 0), c(1, 0), c(0, -1), c(0, 1),
           c(-2, 0), c(2, 0), c(0, -2), c(0, 2),
           c(-1, -1), c(1, 1), c(-1, 1), c(1, -1))
X0 <- rbind(c(0, 0), c(1, 0), c(0, 1), c(0, 0))
NEW <- rbind(c(1, 1), c(-1, 0), c(0, 0))
y <- c(0, 10, 2, -3, 7, -1, 8, 4, 11, -2, 5, 3)
den <- c(1, 3, 2, 1, 4, 2, 3, 1, 2, 4, 1, 3)
D <- cbind(seq_along(y), (-1)^seq_along(y) * (seq_along(y) %% 3L + 1L))
mD <- matrix(.25, nrow(X), 2L)
score <- (D - mD) * (.5 - as.numeric(y <= as.numeric(D %*% c(.25, -.5))))

lines <- c("// Generated by tools/generate_distance_tie_fixtures.R; do not hand edit.",
  "// Native R and forced R fallback must each pass independent subset/deletion references.",
