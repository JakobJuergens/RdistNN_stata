emit <- function(name, value) {
  value <- as.matrix(value)
  rows <- apply(value, 1L, function(z) paste(sprintf("%.17g", z), collapse = ","))
  lines <<- c(lines, sprintf("matrix DT_%s = (%s)", name,
    paste(rows, collapse = paste0(" ", intToUtf8(92L), " "))))
}
emit("X", X); emit("X0", X0); emit("NEW", NEW)
emit("y", y); emit("den", den); emit("D", D); emit("score", score)
metrics <- list(l1 = distance_l1(), l2 = distance_l2(),
  l1_scaled = distance_l1_scaled("custom", scale_vec = c(2, 3)),
  l2_scaled = distance_l2_scaled("custom", scale_vec = c(2, 3)),
  mahalanobis = distance_mahalanobis())
cases <- character()
for (metric in names(metrics)) {
  spec <- metrics[[metric]]
  ctx <- if (is.function(spec$setup)) spec$setup(X) else NULL
  frozen <- spec; frozen$setup <- NULL
  dx <- distance_eval_batch(frozen, X, X0, ctx)
  pdx <- distance_eval_batch(frozen, X, NEW, ctx)
  ranks <- vapply(seq_len(ncol(dx)), function(j) {
    r <- integer(nrow(dx)); r[order(dx[, j], seq_len(nrow(dx)))] <- seq_len(nrow(dx)); r
  }, integer(nrow(dx)))
  emit(paste0(metric, "_dx"), dx)
  emit(paste0(metric, "_ranks"), ranks)
  for (method in c("exact", "asymp")) for (k in 1:2) {
    id <- paste0(metric, "_", method, k)
    np <- oracle(dx, k, 5L, method, matrix(y))
    pair <- oracle(dx, k, 5L, method, cbind(y, den))
    plqr <- oracle(dx, k, 5L, method, score)
    theta <- pair$fit[1L, ] / pair$fit[2L, ]
    ratio_loo <- pair$loo[, seq(1L, 2L * ncol(dx), 2L), drop = FALSE] -
      sweep(pair$loo[, seq(2L, 2L * ncol(dx), 2L), drop = FALSE], 2L, theta, "*")
    ratio_loo <- sweep(ratio_loo, 2L, pair$fit[2L, ], "/")
    ratioV <- covariance(ratio_loo)
    pred <- oracle(pdx, k, 5L, method, matrix(y))
    for (compiled in c(TRUE, FALSE)) {
      options(RdistNN.use_compiled = compiled)
      fit <- suppressWarnings(np_dnn(X = X, X0 = X0, Y = y, distance = frozen,
        ctx = ctx, method = method, k = k, s = 5L, return = c("W", "ranks", "dx")))
      check(fit$W, np$W, paste(id, compiled, "weights"))
      if (!identical(unname(fit$ranks), unname(ranks))) stop(id, ": exact rank mismatch")
      check(matrix(fit$mu, nrow = 1L), np$fit, paste(id, compiled, "NP"))
      check(unname(suppressWarnings(vcov(fit))), np$V, paste(id, compiled, "NP covariance"))
      catfit <- suppressWarnings(cate_dnn(X = X, X0 = X0, pseudo_outcome = y,
        distance = frozen, ctx = ctx, method = method, k = k, s = 5L))
      check(matrix(catfit$tau, nrow = 1L), np$fit, paste(id, compiled, "CATE"))
      check(unname(suppressWarnings(vcov(catfit))), np$V, paste(id, compiled, "CATE covariance"))
      pairfit <- suppressWarnings(affine_ratio_dnn(X = X, X0 = X0, numerator = y,
        denominator = den, distance = frozen, ctx = ctx, method = method, k = k, s = 5L))
      check(matrix(pairfit$theta, nrow = 1L), matrix(theta, nrow = 1L), paste(id, compiled, "ratio"))
      for (j in seq_len(ncol(dx))) check(unname(pairfit$theta_vcov[[j]]),
        matrix(ratioV[j, j]), paste(id, compiled, "ratio covariance", j))
      pfit <- suppressWarnings(plqr_dnn(X = X, X0 = X0, Y = y, D = D, g = rep(0, nrow(X)),
        mD = mD, theta_eval = c(.25, -.5), tau = .5, distance = frozen,
        ctx = ctx, method = method, k = k, s = 5L))
      check(unname(pfit$moment), plqr$fit, paste(id, compiled, "PLQR"))
      check(unname(pfit$moment_se), matrix(sqrt(diag(plqr$V)), nrow = 2L),
        paste(id, compiled, "PLQR uncertainty"))
      p <- suppressWarnings(predict(unserialize(serialize(fit, NULL)), X0 = NEW, se.fit = TRUE))
      check(matrix(p$fit, nrow = 1L), pred$fit, paste(id, compiled, "restored prediction"))
      check(matrix(p$se.fit, nrow = 1L), matrix(sqrt(diag(pred$V)), nrow = 1L),
        paste(id, compiled, "restored uncertainty"))
    }
    emit(paste0(id, "_W"), np$W); emit(paste0(id, "_fit"), np$fit)
    emit(paste0(id, "_V"), np$V); emit(paste0(id, "_ratio"), matrix(theta, nrow = 1L))
    emit(paste0(id, "_ratioV"), ratioV); emit(paste0(id, "_moment"), plqr$fit)
    emit(paste0(id, "_momentV"), plqr$V); emit(paste0(id, "_pred"), pred$fit)
    emit(paste0(id, "_predV"), pred$V)
    cases <- c(cases, id)
  }
  for (method in c("exact", "asymp")) {
    id <- paste0(metric, "_tdnn_", method)
    ref <- oracle(dx, 1L, 3L, method, matrix(y), tdnn = TRUE)
    for (compiled in c(TRUE, FALSE)) {
      options(RdistNN.use_compiled = compiled)
      fit <- suppressWarnings(np_tdnn(X = X, X0 = X0, Y = y, distance = frozen, ctx = ctx,
        method = method, s1 = 3L, s2 = 6L, dim = 2L, return = "W"))
      check(fit$W, ref$W, paste(id, compiled, "signed weights"))
      check(matrix(fit$mu, nrow = 1L), ref$fit, paste(id, compiled, "TDNN"))
      check(unname(suppressWarnings(vcov(fit))), ref$V, paste(id, compiled, "TDNN covariance"))
    }
    emit(paste0(id, "_W"), ref$W); emit(paste0(id, "_fit"), ref$fit)
    emit(paste0(id, "_V"), ref$V)
    cases <- c(cases, id)
  }
}
